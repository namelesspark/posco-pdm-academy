import pandas as pd

df = pd.read_csv('data/16_diecasting.csv', encoding='utf-8')

# 실습 7. 여러 컬럼의 가운데 절반 폭 비교
# 세 컬럼의 Q3~Q1을 비교해 안정·의심 컬럼 구분 : Q1, Q2, Q3
# 세 컬럼의 가운데 절반 폭(Q3~Q1)을 비교 -> quantile()

# 단계
# · 세 컬럼의 사분위수(Q1, Q2, Q3)를 한 번에 구하기 -> 실린더압력, 사이클타임, 비스킷두께
df_q = df[['실린더압력', '사이클타임', '비스킷두께']].quantile([0.25, 0.50, 0.75])
print(df_q)
#        실린더압력   사이클타임  비스킷두께
# 0.25  215.75  20.800   11.0
# 0.50  218.00  22.600   13.0
# 0.75  265.00  35.925   17.0

# · 각 컬럼의 75% 값에서 25% 값을 빼 가운데 절반 폭 계산
# df_q에서 0.75가 index label로 되어있는 row -> df_q.loc[0.75]
print(df_q.loc[0.75] - df_q.loc[0.25])
# 실린더압력    49.250
# 사이클타임    15.125
# 비스킷두께     6.000

# · 폭이 좁은 안정 컬럼과 넓은 의심 컬럼 구분

# 예상 결과
# 폭 실린더압력 49.25·사이클타임 15.12·비스킷두께 6

# 실린더압력 49.25, 사이클타임 15.12, 비스킷두께 6.0 (Q3-Q1 = 다음 시간의 IQR)
