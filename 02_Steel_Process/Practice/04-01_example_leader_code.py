#
# 조건
# 1. 데이터저장여부가 "Y"여야 합니다.
# 2. 저장주기_분을 '일(day)' 단위로 변환하세요.
# 3. 실제 저장 주기가 권장점검주기_일보다 짧거나 같아야 합니다.
#
# 새로운 컬럼 이름은 "저장주기_적정"으로 만드세요.
