# 실습 2 - 고장의 예측 가능성 분류
# ============================================================

# [상황]
# 같은 고장이라도 현장의 대응 리드타임에 따라
# 예측 가능 여부가 달라질 수 있습니다.
#
# 케이스 A : 리드타임 7일
# 케이스 B : 리드타임 30일


# ------------------------------------------------------------
# Step 1. 판정 규칙 만들기
# ------------------------------------------------------------

# [문제]
# 아래 판정 규칙을 함수로 구현하세요.
#
# Q1. 열화 과정이 물리적으로 존재하는가?
# - 손상형태가 "과부하 파단" 또는 "이물"이면
#   → "물리적 돌발"
#
# Q2. P-F 간격이 리드타임보다 긴가?
# - PF간격_일 <= 리드타임이면
#   → "간격 부족형"
#
# Q3. 해당 신호가 데이터에 저장되는가?
# - 데이터저장여부가 "Y"가 아니면
#   → "측정 부재형"
#
# 위 조건에 모두 해당하지 않으면
#   → "예측 가능형"
#
# 함수 이름은 자유롭게 정해도 됩니다.
# 함수는 '한 행'과 '리드타임'을 입력받아
# 판정 문자열을 반환하도록 작성해 보세요.


def 판정(row, lead_time=리드타임):
    if row["손상형태"] in ["과부하파단", "이물"]:
        return "물리적 돌발"
    if row["PF간격_일"] <= lead_time:
        return "간격 부족형"
    if row["데이터저장여부"] == "N":
        return "측정 부재형"
    else:
        return "예측 가능형"


# ------------------------------------------------------------
# Step 2. 케이스 A와 케이스 B 판정
# ------------------------------------------------------------

# [문제]
# 위에서 만든 판정 함수를 사용해
# 두 개의 판정 컬럼을 만드세요.
#
# 케이스 A : 리드타임 7일
#   → 컬럼명 "케이스A_판정"
df["케이스A_판정"] = df.apply(판정, axis=1, lead_time=7)

# 케이스 B : 리드타임 30일
#   → 컬럼명 "케이스B_판정"
df["케이스B_판정"] = df.apply(판정, axis=1, lead_time=30)

# 아래 컬럼을 함께 출력하세요.
