# --- [03-★ 풀코딩] 센서 로그 한 줄 파서 -------------------------------------
# 입력: "  7 , Sensor_02 , WARNING , 0.78912  "
# strip→split(',')→각 조각 정리(id, status 소문자, value 실수 2자리)→ f-string 리포트
log = "  7 , Sensor_02 , WARNING , 0.78912  "
cols = log.strip().split(",")
sid = cols[1].strip()
status = cols[2].strip().lower()
val = float(cols[3].strip())
print(f"[{sid}] 상태={status}, 측정값={val:.2f}")
# 기대: [Sensor_02] 상태=warning, 측정값=0.79


print("\n################  CHAPTER 04 — 리스트 (교안 04_01)  ################")

# --- [04-1] 인덱스로 꺼낸 값 계산 (첫+마지막, 중간값) ----------------------
output = [120, 95, 130, 110, 88, 102]
print(output[0] + output[-1], (output[0] + output[-1]) / 2)
# 기대: 222 111.0

# --- [04-2] 슬라이싱으로 앞/뒤 절반 나누기 ---------------------------------
data = [3, 4, 5, 6, 5, 4, 6, 7, 8, 7, 5, 3]
first = data[:6]
second = data[6:]
print(len(first), len(second))
# 기대: 6 6

# --- [04-3] 잘못된 값을 index로 찾아 바로잡기 ------------------------------
temps = [25, 26, 240, 28, 27]
i = temps.index(240)
temps[i] = 24
print(temps)
# 기대: [25, 26, 24, 28, 27]

# --- [04-4] append / insert / extend -------------------------------------
box = []
box.append(30)  # 끝에 추가
box.insert(0, 28)  # 맨 앞 삽입
box.extend([31, 32])  # 묶음 이어붙이기
print(box)
# 기대: [28, 30, 31, 32]

# --- [04-5] remove / pop / del -------------------------------------------
vals = [25, 26, 999, 24, 28, 26]
vals.remove(999)  # 값으로 제거
x = vals.pop(1)  # 1번 위치 꺼내며 제거
del vals[0]  # 0번 삭제
print(x, vals)
# 기대: 26 [24, 28, 26]

# --- [04-6] sort / reverse / count / index -------------------------------
temps2 = [27, 24, 30, 22, 26, 24, 28]
temps2.sort()  # 오름차순
temps2.reverse()  # 뒤집기
print(temps2.count(24), temps2.index(24))
# 기대: 2 4

# --- [04-7] in / not in 으로 목록 판정 ------------------------------------
machines = ["펌프", "모터", "압축기"]
print("모터" in machines, "밸브" in machines)
# 기대: True False

# --- [04-8] max/min 없이! sort + 인덱스로 최소·최대 -----------------------
temps3 = [27, 24, 30, 22, 26]
temps3.sort()
print(temps3[0], temps3[-1])
# 기대: 22 30

# --- [04-★ 풀코딩] 이상치 정리 + 요약 (리스트 종합 + f-string) -------------
# 원본: [72, 75, 999, 78, 70, 75, 68]  (999는 센서 오류)
# 999 제거 → 개수 → 정렬 후 최소/최대(sort+인덱스) → 75 개수(count) → f-string 요약
readings = [72, 75, 999, 78, 70, 75, 68]
readings.remove(999)
n = len(readings)
readings.sort()
low = readings[0]
high = readings[-1]
c75 = readings.count(75)
print(f"개수={n}, 최소={low}, 최대={high}, 75회수={c75}")
# 기대: 개수=6, 최소=68, 최대=78, 75회수=2
