print("################  CHAPTER 01 — 출력·산술·주석 (교안 01_02)  ################")

# --- [01-1] print 안에서 합계와 평균을 한 줄로 (나눗셈은 float) -----------------
print("합:", 70 + 75 + 80, "| 평균:", (70 + 75 + 80) / 3)
# 기대: 합: 225 | 평균: 75.0

# --- [01-2] 우선순위 함정: 괄호 없이 결과가 32가 되게 (곱셈이 먼저!) -----------
print(2 + 3 * 10)
# 기대: 32

# --- [01-3] 상승량과 그 절반 (빼기, 그리고 나누기 → float) ---------------------
print("상승:", 90 - 68, "| 절반:", (90 - 68) / 2)
# 기대: 상승: 22 | 절반: 11.0

# --- [01-★ 풀코딩] 1호기 점검 리포트 -----------------------------------------
# 조건: 제목 → 기준/현재 온도(이름표와 함께) → 상승량 → 평균, 끝줄에 상태 주석
print("===== 1호기 점검 =====")
print("기준(C):", 68)
print("현재(C):", 85)
print("상승량:", 85 - 68)
print("평균:", (68 + 85) / 2)  # 상태: 주의 관찰
# 기대:
# ===== 1호기 점검 =====
# 기준(C): 68
# 현재(C): 85
# 상승량: 17
# 평균: 76.5


print(
    "\n################  CHAPTER 02 — 변수·자료형·연산자·입력 (교안 02_01~02_04)  ################"
)

# --- [02-1] 다중 할당 + 몫/나머지/거듭제곱 -----------------------------------
