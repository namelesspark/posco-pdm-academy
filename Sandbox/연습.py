# --- [04-★ 풀코딩] 이상치 정리 + 요약 (리스트 종합 + f-string) -------------
#  원본: readings = [72, 75, 999, 78, 70, 75, 68]   (999는 센서 오류)
#  조건 (if/for 없이):
#   - 999 를 리스트에서 제거
#   - 데이터 개수(len)
#   - 정렬 후 최솟값 / 최댓값 (sort + 인덱스, max/min 금지)
#   - 75 가 몇 번 나오는지 count
#   - f-string 한 줄 요약으로 출력
#  기대: 개수=6, 최소=68, 최대=78, 75회수=2
# ── 여기에 코드를 작성하세요 ──
readings = [72, 75, 999, 78, 70, 75, 68]
readings.remove(999)
readings.sort()
data_len = len(readings)
min = readings[0]
max = readings[-1]
count_75 = readings.count(75)

print(f"개수={data_len}, 최소={min}, 최대={max}, 75회수={count_75}")


