# --- [03-★ 풀코딩] 센서 로그 한 줄 파서 -------------------------------------
#  입력: "  7 , Sensor_02 , WARNING , 0.78912  "
#  조건 (배운 문자열 기능 총동원):
#   - strip() 후 ',' 로 4조각 분리
#   - id     : 2번째 조각 공백 제거            → Sensor_02
#   - status : 3번째 조각 공백 제거 + 소문자    → warning
#   - value  : 4번째 조각을 실수로, 소수점 2자리
#   - f-string 한 줄 리포트로 출력
#  기대: [Sensor_02] 상태=warning, 측정값=0.79
# ── 여기에 코드를 작성하세요 ──
sensor_log = "  7 , Sensor_02 , WARNING , 0.78912  "
sensor_log_list = sensor_log.strip().split(",")
id = sensor_log_list[1].strip()
status = sensor_log_list[2].strip().lower()
value = float(sensor_log_list[3].strip())
print(f"{id}, {status}, {value:.2f}")

