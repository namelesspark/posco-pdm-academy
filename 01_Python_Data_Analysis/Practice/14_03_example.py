# 해석 : 온도와 진동의 상관은 0.345로 약한 양의 관계 -> 온도만으로 고장을 설명하기 어려움
# 행동 : 편차가 큰 C라인과 고장이 잦은 A라인을 우선 점검 대상으로 분리해 확인
