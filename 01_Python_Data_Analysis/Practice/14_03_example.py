import pandas as pd
import os

###############################################################################
# 실습 1 - 두 열의 상관계수 구하기
###############################################################################
print("=" * 150, "\n", "=== 실습 1 - 두 열의 상관계수 구하기 ===")
path_1 = os.path.join("Data", "14_hydraulic_qc.csv")
df_1 = pd.read_csv(path_1, encoding="utf-8")

# 데이터를 불러와 앞부분과 구조 확인
print("-" * 150)
print("데이터를 불러와 앞부분과 구조 확인:\n")
print(df_1.info())
print(df_1.head())

# corr로 두 지표의 상관계수 구하기
# 상관계수는 -1 ~ 1 범위이고, 부호는 방향 / 절댓값은 세기를 뜻함
print("-" * 150)
r_1 = df_1["지표07"].corr(df_1["지표08"])
print("corr로 지표07과 지표08의 상관계수 구하기", "\n", "corr():", r_1)

# round로 소수점 셋째 자리까지 정리해 읽기 쉽게 만들기
print("-" * 150)
print("round로 소수점 셋째 자리까지 정리", "\n", "corr().round(3):", r_1.round(3))

# 부호와 절댓값으로 관계 해석하기
# -0.969 -> 부호가 음수이므로 지표07이 오르면 지표08은 내려감
#        -> 절댓값이 1에 매우 가까우므로 강한 음의 상관관계


###############################################################################
# 실습 2 - 상관 행렬로 여러 열 비교
###############################################################################
print("=" * 150, "\n", "=== 실습 2 - 상관 행렬로 여러 열 비교 ===")
path_2 = os.path.join("Data", "14_hydraulic_qc.csv")
df_2 = pd.read_csv(path_2, encoding="utf-8")

# 비교할 지표 열들을 리스트로 묶기
cols = [
    "지표01",
    "지표02",
    "지표03",
    "지표04",
    "지표05",
    "지표06",
    "지표07",
    "지표08",
    "지표09",
    "지표10",
]

# 데이터프레임에 corr을 붙여 모든 조합의 상관계수를 한 번에 구하기
# 대각선은 자기 자신과의 상관이라 항상 1.00
# 대각선 기준으로 위아래가 대칭인 표가 나옴
print("-" * 150)
corr_matrix = df_2[cols].corr()
print("데이터프레임에 corr을 붙여 모든 조합의 상관계수를 한 번에 구하기")
print(corr_matrix.round(2))

# 특정 열 하나만 뽑아 다른 지표들과의 상관을 정렬해서 확인
# 자기 자신(1.00)을 빼고 보면 어떤 지표와 가장 강하게 묶여 있는지 보임
print("-" * 150)
print("지표01 기준으로 다른 지표와의 상관을 내림차순 정렬")
print(corr_matrix["지표01"].sort_values(ascending=False).round(2))


###############################################################################
# 실습 3 - 그룹별 상관 비교
###############################################################################
print("=" * 150, "\n", "=== 실습 3 - 그룹별 상관 비교 ===")
path_3 = os.path.join("Data", "14_hydraulic_qc.csv")
df_3 = pd.read_csv(path_3, encoding="utf-8")

# 전체 데이터의 지표07과 지표08 상관계수
print("-" * 150)
r_all = df_3["지표07"].corr(df_3["지표08"])
print("전체 데이터의 지표07과 지표08 상관계수", "\n", "corr():", r_all.round(3))

# 판정 열로 합격 그룹을 나눠 같은 두 지표의 상관계수 계산
print("-" * 150)
df_pass = df_3[df_3["검사결과"] == "합격"]
r_pass = df_pass["지표07"].corr(df_pass["지표08"])
print(
    "합격 그룹의 지표07과 지표08 상관계수",
    "\n",
    "corr():",
    r_pass.round(3),
    "|표본 수:",
    len(df_pass),
)

# 판정 열로 불합격 그룹을 나눠 같은 두 지표의 상관계수 계산
print("-" * 150)
df_fail = df_3[df_3["검사결과"] == "불합격"]
r_fail = df_fail["지표07"].corr(df_fail["지표08"])
print(
    "불합격 그룹의 지표07과 지표08 상관계수",
    "\n",
    "corr():",
    r_fail.round(3),
    "|표본 수:",
    len(df_fail),
)

# 전체·합격·불합격 상관을 비교하고 표본 수 주의
# 전체 -0.969인데 합격만 보면 0.385로 관계가 약해짐
# 불합격은 -0.998로 두 지표가 거의 완벽하게 반대로 움직임
# 다만 불합격은 12건뿐이라 표본이 적어 값이 과장돼 보일 수 있음 -> 신중히 해석


###############################################################################
# 실습 4 - 통합 리포트 종합
###############################################################################
print("=" * 150, "\n", "=== 실습 4 - 통합 리포트 종합 ===")
path_4 = os.path.join("Data", "14_equipment_sensor.csv")
df_4 = pd.read_csv(path_4, encoding="utf-8")

print("-" * 150)
print("설비 센서 데이터를 불러와 구조 확인:\n")
print(df_4.info())

# 라인으로 그룹을 나눠 측정수·평균온도·온도편차 요약
# agg에 이름을 붙이면 표 그대로 보고서에 붙여도 알아보기 쉬움
report_4 = (
    df_4.groupby("line")
    .agg(
        측정수=("temp", "count"),
        평균온도=("temp", "mean"),
        온도편차=("temp", "std"),
    )
    .round(2)
)

print("-" * 150)
print("라인별 통계")
print(report_4)

# 심각한 정보를 먼저 보여주기 위해 온도편차 기준 내림차순 정렬
print("-" * 150)
print("온도편차가 큰 라인 순으로 정렬")
print(report_4.sort_values("온도편차", ascending=False))

# 온도와 진동의 상관계수를 구해 함께 움직이는지 확인
print("-" * 150)
r_4 = df_4["temp"].corr(df_4["vibration"])
print("온도와 진동의 상관계수", "\n", "corr():", r_4.round(3))

# 고장 행만 걸러 라인별 고장 건수 집계
print("-" * 150)
df_bad = df_4[df_4["result"] == "고장"]
print("라인별 고장 건수")
print(df_bad.groupby("line").size())

