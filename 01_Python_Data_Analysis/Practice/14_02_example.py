import pandas as pd
import os

###############################################################################
# 실습 1 - 평균·분산·표준편차 구하기
###############################################################################
print("=" * 150, "\n", "=== 실습 1 - 평균·분산·표준편차 구하기 ===")
path_1 = os.path.join("Data", "14_hydraulic.csv")
df_1 = pd.read_csv(path_1, encoding="utf-8")

# 진동 열 전체의 평균·분산·표준편차를 각각 구하기
# 대푯값(평균)과 흩어짐(분산·표준편차)을 나타내는 세 통계량
print("-" * 150)
print(
    "진동 열 전체의 평균·분산·표준편차",
    "\n",
    "mean():",
    df_1["진동"].mean().round(3),
    "|var():",
    df_1["진동"].var().round(3),
    "|std():",
    df_1["진동"].std().round(3),
)

# 표준편차를 제곱하면 분산과 같아지는지 확인
print("-" * 150)
print(
    "표준편차를 제곱하면 분산과 같아지는지 확인",
    "\n",
    "std() ** 2:",
    (df_1["진동"].std() ** 2).round(6),
    "|var():",
    df_1["진동"].var().round(6),
)

# 라인으로 그룹을 나눠 라인별 평균과 표준편차 비교 (라인 = 냉각기상태)
print("-" * 150)
print("라인으로 그룹을 나눠 라인별 평균과 표준편차 비교")
print(df_1.groupby("냉각기상태")["진동"].mean().round(3))
print(df_1.groupby("냉각기상태")["진동"].std().round(3))

# agg에 리스트를 넘겨 두 통계를 한 번에 모아보기
print("-" * 150)
print("agg에 리스트를 넘겨 두 통계를 한 번에 모아보기")
print(df_1.groupby("냉각기상태")["진동"].agg(["mean", "std"]).round(3))

# 판다스가 더 권장하는 방식으로 통계 항목별 이름 붙여 정리하기
print("-" * 150)
print("통계 항목별 이름을 붙여 정리하기")
print(
    df_1.groupby("냉각기상태")
    .agg(평균=("진동", "mean"), 표준편차=("진동", "std"))
    .round(3)
)


###############################################################################
# 실습 2 - 그룹별 통계 응용
###############################################################################
print("=" * 150, "\n", "=== 실습 2 - 그룹별 통계 응용 ===")
path_2 = os.path.join("Data", "14_hydraulic_qc.csv")
df_2 = pd.read_csv(path_2, encoding="utf-8")

# 합격·불합격 그룹의 지표 평균과 표준편차 비교 -> 검사결과로 그룹 만들기
feats = ["지표01", "지표05"]

# 판정 열로 그룹을 나눠 주요 지표들의 평균 집계
print("-" * 150)
print("판정 열로 그룹을 나눠 주요 지표들의 평균 집계")
print(df_2.groupby("검사결과")[feats].mean().round(2))

# 같은 그룹 기준으로 표준편차를 구해 흩어짐 비교
print("-" * 150)
print("같은 그룹 기준으로 표준편차를 구해 흩어짐 비교")
print(df_2.groupby("검사결과")[feats].std().round(2))

# 두 그룹의 통계 차이를 읽어 불량의 특징 관찰
# 지표01과 지표05 모두 합격이 불합격보다 표준편차가 훨씬 작다
# -> 합격품은 값이 일정한 범위에 몰려 있고, 불량품은 흩어져 있다는 뜻


###############################################################################
# 실습 3 - agg로 여러 통계 한 번에
###############################################################################
print("=" * 150, "\n", "=== 실습 3 - agg로 여러 통계 한 번에 ===")
path_3 = os.path.join("Data", "14_hydraulic.csv")
df_3 = pd.read_csv(path_3, encoding="utf-8")

# 교대로 그룹을 나눠 진동의 평균·표준편차·최댓값을 리스트로 한 번에 (교대 = 운전부하)
print("-" * 150)
print("교대로 그룹을 나눠 진동의 평균·표준편차·최댓값을 리스트로 한 번에")
print(df_3.groupby("운전부하")["진동"].agg(["mean", "std", "max"]).round(3))

# 이름 붙이기 방식으로 설비별 평균온도·평균진동·측정수 요약 (설비 = 밸브상태)
# count는 몇 개의 온도 데이터가 있는지 세는 용도
print("-" * 150)
print("이름 붙이기 방식으로 설비별 평균온도·평균진동·측정수 요약")
print(
    df_3.groupby("밸브상태")
    .agg(
        평균온도=("온도", "mean"),
        평균진동=("진동", "mean"),
        측정수=("온도", "count"),
    )
    .round(3)
)

# 두 방식의 결과 표 모양 비교
# 리스트 방식은 한 열에 여러 통계를 붙이는 구조
# 이름 붙이기 방식은 통계 항목마다 대상 열을 따로 지정할 수 있음


###############################################################################
# 실습 4 - agg 진단표 만들기
###############################################################################
print("=" * 150, "\n", "=== 실습 4 - agg 진단표 만들기 ===")
path_4 = os.path.join("Data", "14_hydraulic.csv")
df_4 = pd.read_csv(path_4, encoding="utf-8")

# 설비로 그룹을 나눠 측정수·평균온도·온도편차·평균진동·평균압력을 이름 붙여 집계
report_4 = (
    df_4.groupby("밸브상태")
    .agg(
        측정수=("온도", "count"),
        평균온도=("온도", "mean"),
        온도편차=("온도", "std"),
        평균진동=("진동", "mean"),
        평균압력=("압력", "mean"),
    )
    .round(2)
)

print("-" * 150)
print("설비별 진단표")
print(report_4)

# 온도편차를 기준으로 내림차순 정렬
# 편차가 큰 설비를 불안정 후보로 확인 (지연이 8.93으로 최대)
print("-" * 150)
print("온도편차를 기준으로 내림차순 정렬")
print(report_4.sort_values("온도편차", ascending=False))

# 정렬 기준을 바꿔 평균진동 순으로도 확인
print("-" * 150)
print("평균진동을 기준으로 내림차순 정렬")
print(report_4.sort_values("평균진동", ascending=False))


###############################################################################
# 실습 5 - 그룹별 통계량 종합
###############################################################################
print("=" * 150, "\n", "=== 실습 5 - 그룹별 통계량 종합 ===")
path_5 = os.path.join("Data", "14_hydraulic.csv")
df_5 = pd.read_csv(path_5, encoding="utf-8")

# 온도 열의 전체 평균과 표준편차로 기준선 파악
print("-" * 150)
print(
    "온도 열의 전체 평균과 표준편차로 기준선 파악",
    "\n",
    "mean():",
    df_5["온도"].mean().round(2),
    "|std():",
    df_5["온도"].std().round(2),
)

# 라인별 평균(mean)과 중앙값(median)을 함께 구해 치우침 확인
# 평균과 중앙값 차이가 작을수록 튀는 값이 없다는 뜻 (정상: 35.89 vs 35.90)
print("-" * 150)
print("라인별 평균과 중앙값을 함께 구해 치우침 확인")
print(df_5.groupby("냉각기상태")["온도"].agg(["mean", "median"]).round(2))

# 설비 진단표를 온도편차 순으로 정렬해 우선 점검 대상 선정
report_5 = (
    df_5.groupby("밸브상태")
    .agg(
        평균온도=("온도", "mean"),
        온도편차=("온도", "std"),
        평균진동=("진동", "mean"),
    )
    .round(2)
)

print("-" * 150)
print("설비 진단표")
print(report_5)

# 온도편차가 클수록 점검 대상이란 뜻이니까 내림차순으로 정렬
print("-" * 150)
print("온도편차 순으로 정렬해 우선 점검 대상 선정")
print(report_5.sort_values("온도편차", ascending=False))
