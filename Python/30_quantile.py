# 교안 16_01 - 사분위수(quantile)
# 교수님 설명 코드 (실습은 Practice/16_01_example.py)
#
# [핵심] 데이터를 크기순으로 줄 세워 4등분하는 "지점"을 구한다.
#   Q1(0.25) 하위 25% 지점 / Q2(0.50) 중앙값 / Q3(0.75) 상위 25% 지점
#
# [왜 배우나] 다음 단계인 IQR 이상치 탐지의 준비물.
#   IQR = Q3 - Q1
#   이상치 = Q1 - 1.5*IQR 미만  또는  Q3 + 1.5*IQR 초과   (박스플롯 수염이 이것)
#
# [평균/표준편차와의 차이] 사분위수는 극단값에 거의 안 흔들린다.
#   센서가 -999 같은 값 하나만 뱉어도 평균은 망가지지만 중앙값은 그대로.
#   설비 데이터처럼 결측 sentinel·튀는 값이 섞이는 데이터에 사분위수를 쓰는 이유.

import pandas as pd

df = pd.read_csv("Data/16_diecasting.csv", encoding="utf-8")
df = df.dropna()  # 15차시 결측치 처리와 연결. quantile 자체는 NaN을 자동 제외함
df.info()

print(df.describe())

# quantile 계산을 위해 sort 처리는 필요없음 (내부에서 알아서 정렬함)
# df = df.sort_values('주조압력')

print(df["주조압력"].quantile(0.25))  # 595.0
print(df["주조압력"].quantile(0.50))  # 1037.0
print(df["주조압력"].quantile(0.75))  # 1052.0

# 리스트로 넘기면 한 번에 → Series 로 반환
print(df["주조압력"].quantile([0.25, 0.5, 0.75]))
# 0.25     595.0
# 0.50    1037.0
# 0.75    1052.0

# .tolist() 로 파이썬 리스트로 꺼내 쓸 수 있음
print(df["주조압력"].quantile([0.25, 0.5, 0.75]).tolist())
# [595.0, 1037.0, 1052.0]

# [이 출력값 읽는 법]
#   Q1→Q2 간격 442, Q2→Q3 간격 15.
#   → 데이터가 1000~1050 에 몰려 있고 아래쪽으로 꼬리가 긴 분포.
#   → 정상 주조압력은 1000 언저리인데 저압 이상이 꽤 섞여 있다는 뜻.
